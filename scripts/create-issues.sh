  "[CRITICAL] GHSA-55h3-fm53-wq99: Remove malware package eslint-plugin-i18n-strings" \
  "## Security Vulnerability: GHSA-55h3-fm53-wq99\\n\\n**Package:** \`eslint-plugin-i18n-strings\` (npm)\\n**Severity:** CRITICAL\\n**Ecosystem:** npm\\n**Fix version:** No safe version exists — package contains malware\\n\\n### Description\\nThe npm package \`eslint-plugin-i18n-strings\` has been flagged as containing malware (GHSA-55h3-fm53-wq99). This package must be removed from the project entirely.\\n\\n### Remediation Instructions\\n1. Remove \`eslint-plugin-i18n-strings\` from \`superset-frontend/package.json\` (or wherever it is referenced)\\n2. Remove any ESLint configuration that references this plugin\\n3. If custom lint rules from this plugin are in use, migrate them to a safe alternative or implement them as local ESLint rules\\n4. Run \`npm install\` to update the lockfile\\n5. Run the linting and test suites to verify nothing is broken\\n\\n### Acceptance Criteria\\n- [ ] Package \`eslint-plugin-i18n-strings\` completely removed from dependencies and lockfile\\n- [ ] ESLint configuration updated to remove references to this plugin\\n- [ ] Linting still passes (with any rule migrations needed)\\n- [ ] All existing tests pass\\n- [ ] PR links back to this issue\\n\\n---\\n*Auto-generated by Security Remediation Pipeline*"

